def _noop() -> None:
    return None


def _artifacts_projection(
    terminal: AcceptedRun | BlockedRun,
    bundle: GeneratedReportBundle | None,
    verification: None,
    store: FilesystemArtifactStore | None = None,
) -> ArtifactsProjection:
    run_id = terminal.generation_id
    from AgMark.gui.artifact_actions import artifact_actions
    root = store.root if store is not None else None
    rows: dict[str, ArtifactRowProjection] = {}
    observations = {}
    for raw in getattr(terminal, "treatment_observations", ()):
        if not isinstance(raw, bytes):
            continue
        try:
            document = json.loads(raw)
        except (ValueError, UnicodeError):
            continue
        if isinstance(document, Mapping) and isinstance(document.get("observation_id"), str):
            # Link the exact retained canonical observation, which can contain
            # several capture sources. No provider telemetry is decoded here.
            observations["sha256:" + hashlib.sha256(raw).hexdigest()] = (document["observation_id"], len(raw))

    for record in _terminal_records(terminal):
        observation = observations.get(record.sha256) if record.role == "treatment_observation" else None
        actions = artifact_actions(root, run_id, record.reference, record.sha256)
        rows[record.artifact_id] = ArtifactRowProjection(
            artifact_id=record.artifact_id,
            artifact=record.artifact_id,
            artifact_icon="▣",
            artifact_type=record.media_type or record.role,
            status=record.availability,
            status_icon=_status_icon(record.availability),
            integrity_hash=record.sha256,
            size=f"{observation[1]} bytes" if observation else "Unavailable",
            open_action=actions[0],
            reveal_action=actions[1],
            status_semantics=_status_tone(record.availability),
            reference=record.reference,
            capture_invocation_ids=(observation[0],) if observation else (),
            capture_scope="original" if observation else None,
        )

    for component in _report_components(bundle, verification):
        retained_path = PurePosixPath(component.reference).parts[0] == run_id
        if retained_path:
            actions = artifact_actions(root, run_id, component.reference, component.sha256)
        else:
            # Bundle references identify generated bytes, not generation-local
            # disk files. Generation and reconstruction do not persist them.
            unavailable = ArtifactActionProjection(_noop, False,
                "Generated report component has no retained local file. Export the readable report from Reports.")
            actions = (unavailable, unavailable)
        rows[component.artifact_id] = ArtifactRowProjection(
            artifact_id=component.artifact_id,
            artifact=component.artifact_id,
            artifact_icon="▤",
            artifact_type=component.media_type,
            status="retained" if retained_path else "generated",
            status_icon=_status_icon("retained" if retained_path else "generated"),
            integrity_hash=component.sha256,
            size=f"{len(component.data)} bytes",
            open_action=actions[0],
            reveal_action=actions[1],
            status_semantics="success" if retained_path else "neutral",
            reference=component.reference,
        )

    values = tuple(rows.values())
    return ArtifactsProjection(
        run_id=run_id,
        rows=values,
        empty_state=None if values else "No retained artifacts are available for this run.",
    )
