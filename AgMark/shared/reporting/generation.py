"""Deterministic report projection and report-manifest generation."""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass
import json
from types import MappingProxyType
from typing import Final

from ..evaluation.scoring import IdentityRef
from ..runtime.artifacts import sha256_bytes
from .model import (
    REPORT_SCHEMA_ID,
    REPORT_SCHEMA_VERSION,
    CanonicalReportModel,
    ReportArtifactRef,
)


REPORT_MANIFEST_SCHEMA_ID: Final[str] = (
    "arcgrav.shared.schema.report-manifest"
)
REPORT_MANIFEST_SCHEMA_VERSION: Final[str] = "1.0.0"


@dataclass(frozen=True, slots=True)
class GeneratedReportComponent:
    """Exact generated bytes and their storage-neutral retained identity."""

    artifact_id: str
    reference: str
    data: bytes
    media_type: str
    encoding: str
    schema_id: str | None = None
    schema_version: str | None = None

    def __post_init__(self) -> None:
        for value, field in (
            (self.artifact_id, "artifact_id"),
            (self.reference, "reference"),
            (self.media_type, "media_type"),
            (self.encoding, "encoding"),
        ):
            _text(value, field)
        if not isinstance(self.data, bytes):
            raise TypeError("data must be exact bytes")
        if (self.schema_id is None) != (self.schema_version is None):
            raise ValueError("schema_id and schema_version must be provided together")
        if self.schema_id is not None:
            _text(self.schema_id, "schema_id")
            _text(self.schema_version, "schema_version")

    @property
    def sha256(self) -> str:
        return sha256_bytes(self.data)

    def to_artifact_ref(self) -> ReportArtifactRef:
        return ReportArtifactRef(
            artifact_id=self.artifact_id,
            sha256=self.sha256,
            reference=self.reference,
            availability="retained",
            schema_id=self.schema_id,
            schema_version=self.schema_version,
        )


@dataclass(frozen=True, slots=True)
class GeneratedReportBundle:
    """One deterministic machine/human report bundle and report manifest."""

    report_document: Mapping[str, object]
    canonical_evidence_document: Mapping[str, object]
    report_manifest: Mapping[str, object]
    report: GeneratedReportComponent
    canonical_evidence: GeneratedReportComponent
    human: GeneratedReportComponent
    manifest: GeneratedReportComponent

    def __post_init__(self) -> None:
        for value, field in (
            (self.report_document, "report_document"),
            (self.canonical_evidence_document, "canonical_evidence_document"),
            (self.report_manifest, "report_manifest"),
        ):
            if not isinstance(value, Mapping):
                raise TypeError(f"{field} must be a mapping")
        for value, field in (
            (self.report, "report"),
            (self.canonical_evidence, "canonical_evidence"),
            (self.human, "human"),
            (self.manifest, "manifest"),
        ):
            if type(value) is not GeneratedReportComponent:
                raise TypeError(f"{field} must be GeneratedReportComponent")

    @property
    def components(self) -> tuple[GeneratedReportComponent, ...]:
        return (self.report, self.canonical_evidence, self.human)


def generate_report_bundle(
    model: CanonicalReportModel,
    *,
    input_evidence_set_id: str,
    generator: IdentityRef,
    procedure_id: str,
    procedure_version: str,
    command_or_procedure: str,
    report_reference: str,
    canonical_evidence_reference: str,
    human_reference: str,
    manifest_reference: str,
) -> GeneratedReportBundle:
    """Project one canonical model and bind exact generated bytes in a manifest.

    The function performs no I/O. References are caller-supplied output
    locations so benchmark-owned or external stores retain storage authority.
    The report manifest binds exact components to the accepted generation
    and source evidence.
    """

    if type(model) is not CanonicalReportModel:
        raise TypeError("model must be CanonicalReportModel")
    if type(generator) is not IdentityRef:
        raise TypeError("generator must be IdentityRef")
    procedure = IdentityRef(procedure_id, procedure_version)
    for value, field in (
        (input_evidence_set_id, "input_evidence_set_id"),
        (command_or_procedure, "command_or_procedure"),
        (report_reference, "report_reference"),
        (canonical_evidence_reference, "canonical_evidence_reference"),
        (human_reference, "human_reference"),
        (manifest_reference, "manifest_reference"),
    ):
        _text(value, field)

    accepted = model.accepted.accepted
    from .run_report import build_run_results
    run_results = build_run_results(model)
    report_document = _report_document(model, run_results)
    canonical_evidence_document = _canonical_evidence_document(model, run_results)

    report = GeneratedReportComponent(
        artifact_id=f"{model.report_id}:machine-report",
        reference=report_reference,
        data=_canonical_json_bytes(report_document),
        media_type="application/json",
        encoding="utf-8",
        schema_id=REPORT_SCHEMA_ID,
        schema_version=REPORT_SCHEMA_VERSION,
    )
    canonical_evidence = GeneratedReportComponent(
        artifact_id=f"{model.report_id}:canonical-evidence",
        reference=canonical_evidence_reference,
        data=_canonical_json_bytes(canonical_evidence_document),
        media_type="application/json",
        encoding="utf-8",
    )
    human = GeneratedReportComponent(
        artifact_id=f"{model.report_id}:human-report",
        reference=human_reference,
        data=_human_markdown(model, run_results, human_reference=human_reference,
                             report_reference=report_reference,
                             canonical_evidence_reference=canonical_evidence_reference,
                             manifest_reference=manifest_reference),
        media_type="text/markdown",
        encoding="utf-8",
    )

    component_refs = [
        report.to_artifact_ref().to_dict(),
        canonical_evidence.to_artifact_ref().to_dict(),
        human.to_artifact_ref().to_dict(),
    ]
    manifest_document: dict[str, object] = {
        "schema_id": REPORT_MANIFEST_SCHEMA_ID,
        "schema_version": REPORT_MANIFEST_SCHEMA_VERSION,
        "extensions": {},
        "manifest_id": model.report_manifest_id,
        "accepted_generation_id": model.accepted_generation_id,
        "report": report.to_artifact_ref().to_dict(),
        "inputs": [
            ref.to_dict()
            for ref in sorted(
                accepted.accepted_artifact_refs,
                key=lambda value: (value.artifact_id, value.sha256),
            )
        ],
        "input_evidence_set_id": input_evidence_set_id,
        "procedure": {
            "id": procedure.id,
            "version": procedure.version,
            "command_or_procedure": command_or_procedure,
        },
        "generator": _identity_ref(generator),
        "components": component_refs,
        "generated_at": model.generated_at,
    }
    if model.validation_inputs:
        manifest_document["extensions"]["arcgrav.telemetry:validation-inputs"] = [ref.to_dict() for ref in model.validation_inputs]
    manifest = GeneratedReportComponent(
        artifact_id=model.report_manifest_id,
        reference=manifest_reference,
        data=_canonical_json_bytes(manifest_document),
        media_type="application/json",
        encoding="utf-8",
        schema_id=REPORT_MANIFEST_SCHEMA_ID,
        schema_version=REPORT_MANIFEST_SCHEMA_VERSION,
    )
    return GeneratedReportBundle(
        report_document=_freeze_mapping(report_document),
        canonical_evidence_document=_freeze_mapping(canonical_evidence_document),
        report_manifest=_freeze_mapping(manifest_document),
        report=report,
        canonical_evidence=canonical_evidence,
        human=human,
        manifest=manifest,
    )


def _report_document(model: CanonicalReportModel, run_results: Mapping[str, object]) -> dict[str, object]:
    from .run_report import RUN_RESULTS_EXTENSION
    if RUN_RESULTS_EXTENSION in model.extensions:
        raise ValueError("run results projection is reporting-owned")
    accepted = model.accepted.accepted
    return {
        "schema_id": REPORT_SCHEMA_ID,
        "schema_version": REPORT_SCHEMA_VERSION,
        "extensions": {**_thaw(model.extensions), RUN_RESULTS_EXTENSION: _thaw(run_results)},
        "report_id": model.report_id,
        "report_version": model.report_version,
        "accepted_generation_id": model.accepted_generation_id,
        "status": model.status,
        "benchmark": _identity_ref(accepted.benchmark),
        "case_set": _identity_ref(accepted.case_set),
        "treatment_set": _identity_ref(accepted.treatment_set),
        "execution_boundary": accepted.execution_boundary.to_dict(),
        "primary_endpoint": _identity_ref(accepted.primary_endpoint),
        "comparison_track_id": accepted.comparison_track_id,
        "observation_counts": accepted.observation_counts.to_dict(),
        "sections": {
            name: model.sections[name].to_dict()
            for name in model.sections
        },
        "report_manifest_id": model.report_manifest_id,
        "generated_at": model.generated_at,
    }


def _canonical_evidence_document(model: CanonicalReportModel, run_results: Mapping[str, object]) -> dict[str, object]:
    accepted = model.accepted.accepted
    return {
        "report_id": model.report_id,
        "report_version": model.report_version,
        "accepted_generation_id": model.accepted_generation_id,
        "accepted_snapshot_id": accepted.accepted_snapshot_id,
        "artifact_identities": [
            {
                "artifact_id": artifact_id,
                "sha256": digest,
                "reference": reference,
            }
            for artifact_id, digest, reference in model.accepted.artifact_identities
        ],
        "benchmark": _identity_ref(accepted.benchmark),
        "case_set": _identity_ref(accepted.case_set),
        "treatment_set": _identity_ref(accepted.treatment_set),
        "execution_boundary": accepted.execution_boundary.to_dict(),
        "execution_boundary_fingerprint": accepted.execution_boundary_fingerprint,
        "comparison_track_id": accepted.comparison_track_id,
        "primary_endpoint": _identity_ref(accepted.primary_endpoint),
        "metrics": [
            {
                "registration": _thaw(metric.registration),
                "scorer": _identity_ref(metric.scorer),
                "scoring_contracts": [
                    _identity_ref(contract)
                    for contract in metric.scoring_contracts
                ],
            }
            for metric in accepted.metrics
        ],
        "observation_counts": accepted.observation_counts.to_dict(),
        "observation_matrix": [
            {
                "observation_id": entry.observation_id,
                "request_id": entry.request_id,
                "case_id": entry.case_id,
                "treatment_id": entry.treatment_id,
                "repetition_id": entry.repetition_id,
                "execution_boundary_fingerprint": entry.execution_boundary_fingerprint,
                "availability": entry.availability.to_dict(),
                "evidence_refs": [ref.to_dict() for ref in entry.evidence_refs],
            }
            for entry in accepted.observation_matrix
        ],
        "case_result_matrix": [
            {
                "case_id": entry.case_id,
                "treatment_id": entry.treatment_id,
                "execution_boundary_fingerprint": entry.execution_boundary_fingerprint,
                "metric_registration_id": entry.metric_registration_id,
                "metric_registration_version": entry.metric_registration_version,
                "availability": entry.availability.to_dict(),
                "value": _thaw(entry.value),
                "evidence_refs": [ref.to_dict() for ref in entry.evidence_refs],
            }
            for entry in accepted.case_result_matrix
        ],
        "treatment_measurements": _thaw(model.accepted.treatment_measurements),
        "observation_results": _thaw(model.accepted.observation_results),
        "run_results": _thaw(run_results),
        **({"score_details": _thaw(model.accepted.score_details)}
           if model.accepted.score_details else {}),
        "treatment_summaries": [
            {
                "treatment_id": summary.treatment_id,
                "metric_registration_id": summary.metric_registration_id,
                "metric_registration_version": summary.metric_registration_version,
                "availability": summary.availability.to_dict(),
                "planned": summary.planned,
                "finalized": summary.finalized,
                "completed": summary.completed,
                "scorable": summary.scorable,
                "failed": summary.failed,
                "missing": summary.missing,
                "excluded": summary.excluded,
                "non_scorable": summary.non_scorable,
                "numerator": summary.numerator,
                "denominator": summary.denominator,
                "value": _thaw(summary.value),
            }
            for summary in accepted.treatment_summaries
        ],
        "sections": {
            name: model.sections[name].to_dict()
            for name in model.sections
        },
        "status": model.status,
        "extensions": _thaw(model.extensions),
        "generated_at": model.generated_at,
    }


def _human_markdown(
    model: CanonicalReportModel,
    run_results: Mapping[str, object],
    *,
    human_reference: str,
    report_reference: str,
    canonical_evidence_reference: str,
    manifest_reference: str,
) -> bytes:
    from .run_report import render_run_report
    return render_run_report(model, run_results, human_reference=human_reference,
        report_reference=report_reference, canonical_evidence_reference=canonical_evidence_reference,
        manifest_reference=manifest_reference)


def _identity_ref(value: IdentityRef) -> dict[str, object]:
    result: dict[str, object] = {
        "id": value.id,
        "version": value.version,
    }
    if value.sha256 is not None:
        result["sha256"] = value.sha256
    if value.reference is not None:
        result["reference"] = value.reference
    return result


def _canonical_json_bytes(value: object) -> bytes:
    return json.dumps(
        _thaw(value),
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
        allow_nan=False,
    ).encode("utf-8")


def _freeze_mapping(value: Mapping[str, object]) -> Mapping[str, object]:
    return MappingProxyType(
        {key: _freeze(item) for key, item in value.items()}
    )


def _freeze(value: object) -> object:
    if isinstance(value, Mapping):
        return MappingProxyType(
            {str(key): _freeze(item) for key, item in value.items()}
        )
    if isinstance(value, Sequence) and not isinstance(
        value, (str, bytes, bytearray)
    ):
        return tuple(_freeze(item) for item in value)
    return value


def _thaw(value: object) -> object:
    if isinstance(value, Mapping):
        return {str(key): _thaw(item) for key, item in value.items()}
    if isinstance(value, Sequence) and not isinstance(
        value, (str, bytes, bytearray)
    ):
        return [_thaw(item) for item in value]
    return value


def _text(value: object, field: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{field} must be a non-empty string")
    return value


